integration_enabled <- identical(Sys.getenv("NETFS_RUN_INTEGRATION"), "true")

cleanup_remote_file <- function(con, path) {
  try(if (file_exists(path, con)) file_delete(path, con), silent = TRUE)
}

cleanup_remote_dir <- function(con, path) {
  try(if (dir_exists(path, con)) dir_delete(path, con), silent = TRUE)
}

test_that("live SSH backend supports the core workflow", {
  skip_if_not(integration_enabled)
  host <- Sys.getenv("NETFS_TEST_HOST")
  user <- Sys.getenv("NETFS_TEST_USER")
  identity <- Sys.getenv("NETFS_TEST_IDENTITY_FILE")
  root <- paste0("/home/", user, "/netfs-integration")
  con <- ssh(host, user = user, identity_file = identity)
  source <- tempfile(fileext = ".bin")
  payload <- as.raw(c(0L, 1L, 2L, 127L, 255L))
  writeBin(payload, source)
  destination <- tempfile(fileext = ".bin")
  on.exit(unlink(c(source, destination)), add = TRUE)

  if (dir_exists(root, con)) dir_delete(root, con)
  dir_create(root, con)
  on.exit(cleanup_remote_dir(con, root), add = TRUE)
  file_upload(source, root, con)
  remote <- paste0(root, "/", basename(source))
  on.exit(cleanup_remote_file(con, remote), add = TRUE)
  expect_true(file_exists(remote, con))
  expect_true(remote %in% dir_ls(root, con))
  file_download(remote, destination, con)
  expect_identical(readBin(destination, "raw", n = 100L), payload)
  moved <- paste0(root, "/moved.bin")
  file_move(remote, moved, con)
  on.exit(cleanup_remote_file(con, moved), add = TRUE)
  expect_true(file_exists(moved, con))
  file_delete(moved, con)
  dir_delete(root, con)
})

