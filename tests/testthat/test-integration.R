test_that("live cross-connection transfer copies FTP to SMB", {
  skip_if_not(integration_enabled)
  host <- Sys.getenv("NETFS_TEST_HOST")
  user <- Sys.getenv("NETFS_TEST_USER")
  password <- Sys.getenv("NETFS_TEST_PASSWORD")
  share <- Sys.getenv("NETFS_TEST_SMB_SHARE")
  ftp_con <- ftp(host, user = user, password = password)
  smb_con <- smb(host, share, user = user, password = password)
  ftp_root <- "/netfs-transfer-source"
  smb_root <- "/netfs-transfer-destination"
  source <- tempfile(fileext = ".csv")
  writeLines(c("id,value", "1,test"), source, useBytes = TRUE)
  on.exit(unlink(source), add = TRUE)

  dir_create(ftp_root, ftp_con)
  dir_create(smb_root, smb_con)
  on.exit(cleanup_remote_dir(ftp_con, ftp_root), add = TRUE)
  on.exit(cleanup_remote_dir(smb_con, smb_root), add = TRUE)
  file_upload(source, ftp_root, ftp_con)
  ftp_path <- paste0(ftp_root, "/", basename(source))
  on.exit(cleanup_remote_file(ftp_con, ftp_path), add = TRUE)
  result <- file_transfer(ftp_path, smb_root, ftp_con, smb_con)
  on.exit(cleanup_remote_file(smb_con, result), add = TRUE)
  expect_equal(result, paste0(smb_root, "/", basename(source)))
  expect_true(file_exists(result, smb_con))
  file_delete(ftp_path, ftp_con)
  file_delete(result, smb_con)
  dir_delete(ftp_root, ftp_con)
  dir_delete(smb_root, smb_con)
})
